function requireDocx() {
  try { return require('docx'); } catch (e) {}
  const globalPath = path.join(process.env.APPDATA || '', 'npm/node_modules/docx');
  try { return require(globalPath); } catch (e) {}
  throw new Error('docx が見つかりません。このフォルダで `npm install docx` を実行してください。');
}
